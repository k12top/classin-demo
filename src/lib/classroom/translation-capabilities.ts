export function captionTranslationLimit(provider: CaptionTranslationProvider) {
  return provider === "shengwang" ? 10 : 20;
}

export function supportedCaptionTranslationCodes(provider: CaptionTranslationProvider): readonly string[] {
  return provider === "shengwang" ? shengwangTranslationLanguages.map(language => language.code) : wordlyTranslationCodes;
}

export function supportsCaptionTranslation(provider: CaptionTranslationProvider, code: string): boolean {
  return supportedCaptionTranslationCodes(provider).includes(code);
}
